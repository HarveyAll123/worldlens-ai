const byDomain = new Map(REAL_SOURCES.map((s) => [s.domain, s]));

/** Match a hostname (e.g. "www.reuters.com", "edition.cnn.com") to a registry entry. */
export function sourceForDomain(host: string): NewsSource | null {
  let h = host.toLowerCase().replace(/^www\./, '');
  while (h.includes('.')) {
    const hit = byDomain.get(h);
    if (hit) return hit;
    h = h.slice(h.indexOf('.') + 1);
  }
  return null;
}
