/**
 * Curated historical events (1800 →). Real events only.
 *
 * Editorial rules:
 *  - Dates carry only the precision that is well established; uncertain end dates are omitted.
 *  - Coordinates are city/site level (or "approximate"/"region" where noted) — camera targets,
 *    not survey positions.
 *  - Summaries are short and conservative; "why it mattered" avoids asserting causation
 *    beyond what standard references state.
 *  - Every event links to its English Wikipedia article as the "Learn more" destination.
 *    Wikipedia is a convenience reference, not the sole source of truth for the data model.
 */
import type { EventCategory, Participant, WorldEvent } from '../schemas';
import type { Granularity } from '../temporal';

type LocPrecision = 'exact' | 'city' | 'region' | 'country' | 'approximate';

interface Def {
  id: string;
  title: string;
  start: string;
  end?: string;
  precision: Granularity;
  label?: string;
  approximate?: boolean;
  place: string;
  lat: number;
  lon: number;
  loc?: LocPrecision;
  iso3?: string;
  category: EventCategory;
  importance: 1 | 2 | 3 | 4 | 5;
  wiki: string;
  summary: string;
  why: string;
  participants?: Array<[string, Participant['type']]>;
  tags?: string[];
  conflictId?: string;
}

const P = (name: string, type: Participant['type']): Participant => ({ name, type });

function build(d: Def): WorldEvent {
  const wikiUrl = `https://en.wikipedia.org/wiki/${encodeURIComponent(d.wiki.replace(/ /g, '_'))}`;
  return {
    id: d.id,
    kind: 'historical',
    isDemo: false,
    title: d.title,
    summary: d.summary,
    whyItMatters: d.why,
    category: d.category,
    tags: d.tags ?? [],
    time: {
      start: d.start,
      ...(d.end ? { end: d.end } : {}),
      precision: d.precision,
      approximate: d.approximate ?? false,
      ...(d.label ? { label: d.label } : {}),
    },
    location: {
      name: d.place,
      lat: d.lat,
      lon: d.lon,
      precision: d.loc ?? 'city',
      ...(d.iso3 ? { countryCode: d.iso3 } : {}),
      confidence: d.loc === 'approximate' || d.loc === 'region' ? 0.7 : 0.95,
    },
    extraLocations: [],
    participants: (d.participants ?? []).map(([n, t]) => P(n, t)),
    wikipediaTitle: d.wiki,
    references: [
      {
        title: `${d.wiki.replace(/_/g, ' ')} — Wikipedia`,
        url: wikiUrl,
        publisher: 'Wikipedia',
        kind: 'encyclopedia',
        license: 'CC BY-SA 4.0',
      },
    ],
    importance: d.importance,
    confidence: 1,
    ...(d.conflictId ? { conflictId: d.conflictId } : {}),
    articleCount: 0,
    sourceCount: 0,
    hasTakeAction: false,
    provenance: {
      provider: 'curated',
      note: 'WorldLens curated dataset (see CONTENT_LICENSING.md)',
    },
  };
}

